@app.cell
def _(glob, mo, os, pathlib):
    # Search all potential directories across the architecture
    search_patterns = [
        os.path.join("docs", "public", "*"),
        os.path.join("public", "*"),
        os.path.join("data", "runs", "*"),
    ]

    all_runs = []
    for pattern in search_patterns:
        found_paths = glob.glob(pattern)
        valid_dirs = [
            p
            for p in found_paths
            if os.path.isdir(p) and not os.path.basename(p).startswith(".")
        ]
        all_runs.extend(valid_dirs)

    if all_runs:
        # LOCAL PERSPECTIVE: Sort by creation/modification timestamp
        all_runs.sort(key=os.path.getmtime)
        run_names = [os.path.basename(r) for r in all_runs]
        run_choices = list(reversed(run_names))
        latest_run_name = run_choices[0]

        # Build the local lookup map for absolute paths
        local_run_maps = {
            r: str(pathlib.Path(all_runs[run_names.index(r)]).resolve())
            for r in run_choices
        }
    else:
        # WASM PERSPECTIVE: Fallback production list on the web
        run_choices = [
            "8_KnockoutFinal_Ensemble",
            "7_KnockoutSemiFinal_Ensemble",
            "6_KnockoutQuarterFinal_Ensemble",
            "5_KnockoutRound16_Ensemble",
            "4_KnockoutRound32_Ensemble",
            "3_GroupRound3_Ensemble",
            "2_GroupRound2_Ensemble",
            "1_Tournament_Ensemble_Ridge",
            "1_Tournament_Ensemble_SLSQP",
            "1_Tournament_XGBoost_Regressor",
            "1_Tournament_Dynamic_Elo_Rating",
            "1_Tournament_Poisson_Dixon_Coles",
        ]
        latest_run_name = "1_Tournament_Ensemble_Ridge"
        local_run_maps = {}

    def _clean_display_name(folder_name: str) -> str:
        parts = folder_name.split("_")
        if len(parts) >= 2:
            milestone = f"{parts[0]} {parts[1]}"
            model_info = " ".join(parts[2:]) if len(parts) > 2 else ""
            return f"{milestone} 🏆 ({model_info})" if model_info else f"{milestone} 🏆"
        return folder_name

    run_dropdown = mo.ui.dropdown(
        options={_clean_display_name(r): r for r in run_choices},
        value=_clean_display_name(latest_run_name),
        label="📂 SIMULATION RUN",
    )

    # Return the lookup map to the DAG graph
    return local_run_maps, run_dropdown


@app.cell
def _(PUBLIC_DIR, mo, json, local_run_maps, os, pd, run_dropdown):
    import io
    import urllib.request

    run_id = run_dropdown.value

    is_local = not PUBLIC_DIR.startswith("http")

    def get_data_path(filename: str):
        if is_local and run_id in local_run_maps:
            return os.path.join(local_run_maps[run_id], filename)
        else:
            base_url = str(PUBLIC_DIR).rstrip("/")
            return f"{base_url}/{run_id}/{filename}"

    # Centralized robust loading wrapper to strip browser/CDN compression conflicts
    def load_csv(filename: str):
        path = get_data_path(filename)
        if is_local:
            return pd.read_csv(path)
        else:
            # Web Mode: Fetch raw string over HTTP to isolate Pandas from CDN headers
            with urllib.request.urlopen(path) as response:
                raw_data = response.read().decode("utf-8")
            return pd.read_csv(io.StringIO(raw_data))

    # 1. CORE DETERMINISTIC INGESTION
    try:
        df_tournament = load_csv("deterministic_tournament.csv")
        df_tables = load_csv("deterministic_group_tables.csv")
        df_thirds = load_csv("deterministic_third_places.csv")
        df_capabilities = load_csv("pre_tournament_capabilities.csv")
    except Exception as e:
        import urllib.error

        if not is_local and isinstance(e, urllib.error.HTTPError) and e.code == 404:
            mo.stop(
                True,
                mo.md(
                    f"""
                    <div style="background: #1a1a1a; padding: 30px; border-radius: 8px; border: 1px solid #f4b41a; text-align: center; font-family: monospace;">
                        <h3 style="color: #f4b41a; margin-top: 0;">⏳ STAGE LOCKED</h3>
                        <p style="color: #888; font-size: 13px;">
                            The run configurations for <b>{run_id}</b> haven't been compiled yet.<br>
                            Predictions for this node will unlock live as the tournament transitions into this phase!
                        </p>
                    </div>
                    """
                ),
            )

        # Fallback for genuine data corruption or missing critical local files
        raise RuntimeError(
            f"🚨 CRITICAL DATA FETCH ERROR: Unable to load run sequence '{run_id}'."
        ) from e

    # --- UN-FLOODABLE DETERMINISTIC DISCIPLINARY IMPUTATION ALLOCATION ---
    if "red_cards" in df_tournament.columns:
        # 1. Isolate only upcoming fixtures (unplayed games have valid corner predictions)
        is_unplayed = df_tournament["corners"].notna()
        n_unplayed = is_unplayed.sum()

        if n_unplayed > 0:
            # 2. Establish baseline unplayed expectations to prevent future warping
            # (10 expected reds / 104 total matches in 2026 layout ≈ 0.096 per game)
            baseline_red_rate = 10 / 104
            allocated_pool_size = int(round(n_unplayed * baseline_red_rate))

            # Ensure all unplayed matches default back to 0 before distribution
            df_tournament.loc[is_unplayed, "red_cards"] = 0

            if allocated_pool_size > 0:
                # 3. Target ONLY the highest-volatility unplayed matches
                top_fiery_unplayed_indices = (
                    df_tournament[is_unplayed]
                    .sort_values(
                        by=["yellow_cards", "match_id"], ascending=[False, True]
                    )
                    .head(allocated_pool_size)
                    .index
                )
                # Divvy out the integer red cards
                df_tournament.loc[top_fiery_unplayed_indices, "red_cards"] = 1

    # OPTIONAL STOCHASTIC MODELS (Graceful failover guards)
    try:
        df_matchups = load_csv("stochastic_sandbox_matchups.csv")
    except Exception:
        df_matchups = pd.DataFrame(
            columns=[
                "home_team",
                "away_team",
                "venue_country",
                "ensemble_lambda_home",
                "ensemble_lambda_away",
            ]
        )

    try:
        df_forecast = load_csv("stochastic_forecast.csv")
        df_xtables = load_csv("stochastic_group_tables.csv")
        df_tournament_stoch = load_csv("stochastic_tournament.csv")
        has_stochastic = True
    except Exception:
        df_forecast, df_xtables, df_tournament_stoch = None, None, None
        has_stochastic = False

    # 3. RUNTIME PARAMETERS METADATA PARSING
    metadata_path = get_data_path("metadata.json")
    if is_local:
        try:
            with open(metadata_path, "r") as f:
                metadata = json.load(f)
        except Exception:
            metadata = {}
    else:
        try:
            # Isolate the JSON stream analyzer from transport headers as well
            with urllib.request.urlopen(metadata_path) as response:
                raw_json = response.read().decode("utf-8")
            metadata = json.loads(raw_json)
        except Exception:
            metadata = {}

    config = metadata.get("config", {"model_type": "blend"})
    weights = metadata.get(
        "ensemble_weights", {"poisson": 0.33, "elo": 0.33, "xgb": 0.34}
    )
    match_rules = metadata.get(
        "match_rules", {"et_multiplier": 1.0 / 3.0, "fatigue_factor": 0.80}
    )
    return (
        config,
        df_capabilities,
        df_forecast,
        df_matchups,
        df_tables,
        df_thirds,
        df_tournament,
        df_tournament_stoch,
        df_xtables,
        has_stochastic,
        match_rules,
        run_id,
        weights,
    )


